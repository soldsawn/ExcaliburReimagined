    /// <summary>True when the text fits the 16 px icon in this style (at most two glyphs we have).</summary>
    public static bool CanDraw(string text, DigitStyle style)
    {
        var set = style == DigitStyle.Bold ? Bold : Thin;
        return text.Length is 1 or 2 && text.All(set.ContainsKey) && Width(text, set) <= Size;
    }

    /// <summary>Draws the text centred into a 16x16 bitmap; call <see cref="CanDraw"/> first.</summary>
    public static void Draw(Bitmap bmp, string text, Color color, DigitStyle style)
    {
        var set = style == DigitStyle.Bold ? Bold : Thin;
        int x = (Size - Width(text, set)) / 2, y = (Size - Rows) / 2 + 1;
        foreach (char ch in text)
        {
            var glyph = set[ch];
            for (int r = 0; r < Rows; r++)
                for (int c = 0; c < glyph[r].Length; c++)
                {
                    double a = glyph[r][c] switch { '#' => 1, '+' => Corner, _ => 0 };
                    if (a > 0) bmp.SetPixel(x + c, y + r, Color.FromArgb((int)(color.A * a), color));
                }
            x += glyph[0].Length + Gap;
        }
    }

    private static int Width(string text, Dictionary<char, string[]> set) =>
        text.Sum(ch => set[ch][0].Length) + (text.Length - 1) * Gap;
}
