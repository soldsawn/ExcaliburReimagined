using System.Drawing;

namespace Excalibur.App.Tray;

public enum DigitStyle
{
    /// <summary>1 px strokes, the weight of the Windows volume/network icons (default).</summary>
    Thin,
    /// <summary>2 px strokes, HWiNFO/Afterburner style; easier to read from afar.</summary>
    Bold,
}

/// <summary>
/// Hand-drawn digits for the 16 px tray icon. Fonts are anti-aliased into grey smudges at this
/// size; pixel glyphs stay as crisp as the system icons (the approach of HWiNFO, Core Temp,
/// Afterburner). '#' is a full pixel, '+' a half-covered corner pixel, '.' empty. 11 rows high.
/// </summary>
internal static class PixelDigits
{
